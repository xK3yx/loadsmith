// Pure transform for `npm run sync-research`: turns rows from the Terraria
// Wiki's Cargo "Items" table into research amounts keyed by TEdit item key.

import { z } from 'zod'
import type { ItemRecord } from '../src/data/types.ts'

export const WIKI_API = 'https://terraria.wiki.gg/api.php'

const Row = z.object({
  itemid: z.string(),
  name: z.string(),
  research: z.string(),
})
export type WikiRow = z.infer<typeof Row>

export const CargoPage = z.object({
  cargoquery: z.array(z.object({ title: Row })),
})

export interface ResearchEntry {
  key: string
  amount: number
}

export interface ResearchResult {
  entries: ResearchEntry[]
  /** Rows dropped because the ID or name didn't match TEdit's data. */
  skipped: { itemid: string; name: string; reason: string }[]
}

function norm(s: string): string {
  return s
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '')
}

/**
 * Matches wiki rows to TEdit items by ID and name. Some IDs have several wiki
 * rows (console-only items share IDs with PC items), so a row only counts
 * when its name matches TEdit's name for that ID. Rows with no numeric
 * research amount (items that can't be researched) are left out.
 */
export function transformResearch(rows: readonly WikiRow[], items: readonly ItemRecord[]): ResearchResult {
  const byId = new Map(items.map((i) => [i.id, i]))
  const amounts = new Map<string, { id: number; amount: number }>()
  const skipped: ResearchResult['skipped'] = []

  for (const row of rows) {
    if (!/^\d+$/.test(row.itemid)) continue // set pages, not items
    if (!/^\d+$/.test(row.research)) continue // not researchable
    const item = byId.get(Number(row.itemid))
    if (!item || !item.key) {
      skipped.push({ itemid: row.itemid, name: row.name, reason: 'no TEdit item with this ID' })
      continue
    }
    if (norm(item.name) !== norm(row.name)) {
      skipped.push({ itemid: row.itemid, name: row.name, reason: `TEdit calls ${item.id} "${item.name}"` })
      continue
    }
    const amount = Number(row.research)
    const prev = amounts.get(item.key)
    if (prev && prev.amount !== amount) {
      throw new Error(`Wiki gives ${item.name} two research amounts: ${prev.amount} and ${amount}`)
    }
    amounts.set(item.key, { id: item.id, amount })
  }

  const entries = [...amounts.entries()]
    .sort((a, b) => a[1].id - b[1].id)
    .map(([key, { amount }]) => ({ key, amount }))
  return { entries, skipped }
}

export function formatResearch(entries: readonly ResearchEntry[], retrieved: string): string {
  const head = {
    $comment:
      'Journey Mode research amounts from the Terraria Wiki (CC BY-NC-SA; numbers only, credited). Generated by npm run sync-research; do not edit. Hand fixes go in research-overrides.json. Entries may carry since/until save versions. UNVERIFIED in-game: see PLAN.md.',
    source: 'https://terraria.wiki.gg/wiki/Journey_Mode#Research (Cargo table Items.research)',
    retrieved,
  }
  const lines = entries.map((e) => `    ${JSON.stringify(e)}`).join(',\n')
  const top = JSON.stringify(head, null, 2).slice(0, -2) // drop closing "\n}"
  return `${top},\n  "entries": [\n${lines}\n  ]\n}\n`
}
