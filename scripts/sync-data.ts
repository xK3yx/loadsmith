// npm run sync-data [-- --ref <git ref>] [-- --check]
//
// Downloads items.json, prefixes.json and versions.json from TEdit's
// src/TEdit.Terraria/Data/ at the commit pinned in scripts/tedit-source.json,
// validates and trims them, and writes src/data/tedit/.
//
//   --ref <ref>  Resolve <ref> (branch, tag or sha) to a commit, sync from it
//                and update the pin. Use `--ref master` after a Terraria update.
//   --check      Don't write anything. Exit 1 if the files would change.
//                Used by the weekly version check in CI.

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DATA_FILES, TEDIT_DATA_PATH, TEDIT_REPO, formatJson, transform } from './sync-data-lib.ts'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PIN_FILE = join(ROOT, 'scripts', 'tedit-source.json')
const OUT_DIR = join(ROOT, 'src', 'data', 'tedit')

interface Pin {
  repo: string
  commit: string
  date: string
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name)
  return i === -1 ? undefined : process.argv[i + 1]
}

async function getJson(url: string): Promise<unknown> {
  const res = await fetch(url, { headers: { 'User-Agent': 'loadsmith-sync-data' } })
  if (!res.ok) throw new Error(`GET ${url} failed: ${res.status} ${res.statusText}`)
  return res.json()
}

async function resolveRef(ref: string): Promise<Pin> {
  const data = (await getJson(`https://api.github.com/repos/${TEDIT_REPO}/commits/${encodeURIComponent(ref)}`)) as {
    sha: string
    commit: { committer: { date: string } }
  }
  return { repo: TEDIT_REPO, commit: data.sha, date: data.commit.committer.date }
}

function sourceMd(pin: Pin): string {
  return `# Game data from TEdit

These files are generated by \`npm run sync-data\`. Do not edit them by hand.

- Source: https://github.com/${pin.repo}/tree/${pin.commit}/${TEDIT_DATA_PATH}
- Commit: \`${pin.commit}\` (${pin.date})
- Files: ${DATA_FILES.join(', ')} (validated and trimmed to the fields Loadsmith uses)

The data comes from TEdit by the TEdit contributors and is used under the
Microsoft Public License (MS-PL). See the repository LICENSE.
`
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check')
  const ref = arg('--ref')
  const pin: Pin = ref ? await resolveRef(ref) : (JSON.parse(await readFile(PIN_FILE, 'utf8')) as Pin)

  const outputs = new Map<string, string>()
  for (const file of DATA_FILES) {
    const url = `https://raw.githubusercontent.com/${pin.repo}/${pin.commit}/${TEDIT_DATA_PATH}/${file}`
    outputs.set(file, formatJson(transform(file, await getJson(url))))
  }
  outputs.set('SOURCE.md', sourceMd(pin))

  let changed = 0
  for (const [file, text] of outputs) {
    const path = join(OUT_DIR, file)
    const old = await readFile(path, 'utf8').catch(() => null)
    if (old === text) continue
    changed++
    console.log(`${check ? 'would update' : 'updated'} src/data/tedit/${file}`)
    if (!check) {
      await mkdir(dirname(path), { recursive: true })
      await writeFile(path, text)
    }
  }
  if (!check && ref) await writeFile(PIN_FILE, formatJson(pin))

  console.log(`TEdit ${pin.commit.slice(0, 7)} (${pin.date}): ${changed} file(s) ${check ? 'differ' : 'changed'}.`)
  if (check && changed > 0) process.exit(1)
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err)
  process.exit(1)
})
