//
// Classes, per the Terraria Wiki's Modifiers page:
//   melee            swords, shortswords: melee + common + universal modifiers
//   whip             whips use the melee set too (not the 1.4.5 summon set)
//   melee-universal  spears, flails, yoyos, boomerangs: universal only
//   terrarian        universal + the Terrarian's own Legendary (prefix 84)
//   ranged           ranged + common + universal
//   magic            magic + common + universal
//   summon           minion and sentry staffs: summon (1.4.5+) + universal
//                    without crit
//
// Deliberately left out until verified: Daybreak, Psycho Knife, Shadowflame
// Knife, Light Disc and Bananarang (the last two stack), and all 1.4.5 weapons.

